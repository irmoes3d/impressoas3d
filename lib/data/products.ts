export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(categorySlug: string) {
  return products.filter((p) => p.categorySlug === categorySlug);
}

export function getBestSellers() {
  return [...products].sort((a, b) => b.soldCount - a.soldCount).slice(0, 8);
}

export function getNewArrivals() {
  return [...products].sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1)).slice(0, 8);
}

export function getFeaturedForYou() {
  return [...products].filter((p) => p.ratingAvg >= 4.7).slice(0, 8);
}
